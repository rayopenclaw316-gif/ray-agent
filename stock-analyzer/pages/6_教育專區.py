with tab1:
    st.header("財務比率")

    with st.expander("P/E 本益比（Price-to-Earnings Ratio）", expanded=True):
        st.markdown("""
**白話解說**

就像你花 20 萬買一家小吃攤，它每年純賺 1 萬，那你要「回本」需要 20 年。P/E 就是這個概念：
> 「用現在的股價，買這家公司的一份獲利，需要幾年回本？」

**計算公式**
```
P/E = 每股股價 ÷ 每股盈餘（EPS）
```

**計算範例**
```
台積電股價 = 900 元
今年預估 EPS = 45 元
P/E = 900 ÷ 45 = 20 倍
```

**判讀標準**
| P/E 區間 | 意義 |
|----------|------|
| < 10 倍  | 偏低，可能低估，或市場擔憂成長性 |
| 10–20 倍 | 合理區間（多數傳產、金融股） |
| 20–30 倍 | 偏高，需要有成長性支撐 |
| > 30 倍  | 昂貴，適合高成長股，有估值泡沫風險 |

**注意事項**
- P/E 只有在公司有獲利時才有意義，虧損公司無法計算
- 不同產業本益比差異大（科技股通常比傳產高）
- 成長股可接受較高 P/E（未來 EPS 成長 → P/E 自然降低）
""")

    with st.expander("P/B 股價淨值比（Price-to-Book Ratio）"):
        st.markdown("""
**白話解說**

「帳面價值」就是公司把所有資產賣掉、還清所有債務後剩下的錢。P/B 告訴你：
> 「你花多少倍的帳面價值在買這家公司？」

P/B = 1 就是「用帳面價值買」；P/B = 3 就是「花 3 倍帳面價值買」。

**計算公式**
```
P/B = 每股股價 ÷ 每股帳面淨值
每股帳面淨值 = 股東權益 ÷ 流通股數
```

**判讀標準**
| P/B | 意義 |
|-----|------|
| < 1 | 股價低於清算價值，可能低估，但要確認資產是否有問題 |
| 1–2 | 合理 |
| 2–5 | 偏高，但若 ROE 高則合理（高回報企業值高溢價） |
| > 5 | 品牌溢價或市場過度樂觀 |

**搭配 ROE 使用**
> ROE 高的公司，較高的 P/B 是合理的。
> 粗略判斷：合理 P/B ≈ ROE ÷ 必要報酬率
""")

    with st.expander("ROE 股東權益報酬率（Return on Equity）"):
        st.markdown("""
**白話解說**

就像評估一家工廠「每投入 100 萬，能賺多少錢」。
ROE = 20% 代表你投入 100 萬的股東資金，公司每年能賺回 20 萬。

**計算公式**
```
ROE = 淨利 ÷ 股東權益 × 100%
```

**杜邦分解（更深入理解）**
```
ROE = 淨利率 × 資產周轉率 × 財務槓桿
     （賺多少）   （轉得快不快）  （借了多少槓桿）
```

**判讀標準**
| ROE | 意義 |
|-----|------|
| ≥ 20% | 優秀（巴菲特標準） |
| 15–20% | 良好 |
| 8–15%  | 普通 |
| < 8%   | 偏低 |

**注意**：高財務槓桿也會拉高 ROE，需搭配負債比率一起看
""")

    with st.expander("現金流品質：OCF vs 淨利"):
        st.markdown("""
**白話解說**

淨利（Net Income）是「會計帳上的獲利」，但不代表真的收到現金。
就像你開店記了一筆 10 萬的應收帳款，帳上賺了，但錢還沒到手。

> 「現金流品質 = 帳上的錢有多少真正變成口袋裡的錢」

**計算公式**
```
現金流品質比率 = 營業現金流（OCF）÷ 淨利（Net Income）
```

**判讀標準**
| 比率  | 意義 |
|-------|------|
| ≥ 1.0 | 優良：現金收入超過帳面獲利 |
| 0.7–1.0 | 正常：略有應計項目 |
| < 0.7 | 警示：大量未收到現金的紙上富貴 |
| 負值  | 危險：賺錢卻燒錢，需查清楚原因 |

**常見陷阱**
- 公司認列大量「長期合約收入」但實際款項未收
- 存貨囤積（製造業常見）
- 應收帳款爆增但未收款
""")

    with st.expander("毛利率 / 營業利益率 / 淨利率"):
        st.markdown("""
**白話解說**

想像一家麵包店：
- 賣一個麵包 50 元
- 麵粉等原料成本 20 元 → **毛利 30 元，毛利率 60%**
- 再扣掉店租、員工薪水 15 元 → **營業利益 15 元，營業利益率 30%**
- 再扣掉利息、稅後 → **淨利 12 元，淨利率 24%**

**三層公式**
```
毛利率    = （營收 - 直接成本）÷ 營收
營業利益率 = （毛利 - 費用）÷ 營收
淨利率    = 淨利 ÷ 營收
```

**各產業毛利率參考**
| 產業 | 典型毛利率 |
|------|-----------|
| 半導體（台積電）| 50–55% |
| 電子代工（鴻海）| 5–8%   |
| 金融保險 | 依產品而異 |
| 零售百貨 | 30–40%  |
""")

    with st.expander("負債比 / 流動比率 / 速動比率"):
        st.markdown("""
**負債權益比（D/E Ratio）**
```
D/E = 總負債 ÷ 股東權益
```
- D/E < 1：負債少，財務穩健
- D/E 1–2：適中，需看產業
- D/E > 3：財務槓桿高，利率風險大

**流動比率**（短期償債能力）
```
流動比率 = 流動資產 ÷ 流動負債
```
- > 2：充裕，短期無還債壓力
- 1–2：尚可
- < 1：可能有短期流動性問題

**速動比率**（更嚴格，排除存貨）
```
速動比率 = （流動資產 - 存貨）÷ 流動負債
```
- 通常需 > 1 才算安全
""")

