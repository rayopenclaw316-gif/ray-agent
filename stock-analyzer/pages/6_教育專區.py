with tab3:
    st.header("籌碼指標")

    with st.expander("三大法人買賣超", expanded=True):
        st.markdown("""
**誰是三大法人？**
| 法人 | 說明 |
|------|------|
| 外資（外國機構投資人）| 外國基金、投資銀行，資金規模最大，影響力最強 |
| 投信（台灣本土基金）| 本土基金公司（如元大、群益），季末常有作帳行情 |
| 自營商 | 券商用自己的錢炒股，操作較短線 |

**白話解說**

三大法人同時「淨買超」（買進 > 賣出），通常是股票上漲的助燃劑。
外資連續買超尤其重要，因為外資資金最大、眼光最長遠。

**判讀**
- 外資連續 5 天以上淨買超 → 中期看好訊號
- 三大法人同步買超 → 籌碼集中，強度更高
- 法人買超但股價不漲 → 可能有大戶出貨，或消化壓力

**注意**
- 法人資料為每日收盤後公布，有 1 天延遲
""")

    with st.expander("融資融券"):
        st.markdown("""
**融資（買超的槓桿）**

融資 = 用自己的錢 + 向券商借錢買股票。
例：一張股票 10 萬元，自備 6 萬，向券商借 4 萬（融資成數 40%）。

- **融資餘額上升** → 散戶樂觀、加槓桿
- **融資餘額快速上升後轉降** → 多頭力竭，需注意
- **融資斷頭** → 股價跌太多，被強制賣出，會加速下跌

**融券（做空的工具）**

融券 = 向券商借股票賣出，等股價跌後再買回還券，賺差價。

- **融券餘額高** → 市場有做空力量，壓制股價
- **軋空（Short Squeeze）** → 股價上漲，空方被迫買回，反而推升股價

**融資融券比（券資比）**
```
券資比 = 融券張數 ÷ 融資張數 × 100%
```
- 券資比高（> 30%）→ 空方強，多空對立激烈
- 券資比低（< 10%）→ 多方主導，空方不敢進場
""")

