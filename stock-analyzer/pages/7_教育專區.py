with tab1:
    st.header("財務比率")

    with st.expander("P/E 本益比（Price-to-Earnings Ratio）", expanded=True):
        st.markdown("""
**白話解說**

就像你花 20 萬買一家小吃攤，它每年純賺 1 萬，那你要「回本」需要 20 年。P/E 就是這個概念：
> 「用現在的股價，買這家公司的一份獲利，需要幾年回本？」

**計算公式**
```
P/E = 每股股價 ÷ 每股盈餘（EPS）
```

**計算範例**
```
台積電股價 = 900 元
今年預估 EPS = 45 元
P/E = 900 ÷ 45 = 20 倍
```

**判讀標準**
| P/E 區間 | 意義 |
|----------|------|
| < 10 倍  | 偏低，可能低估，或市場擔憂成長性 |
| 10–20 倍 | 合理區間（多數傳產、金融股） |
| 20–30 倍 | 偏高，需要有成長性支撐 |
| > 30 倍  | 昂貴，適合高成長股，有估值泡沫風險 |

**注意事項**
- P/E 只有在公司有獲利時才有意義，虧損公司無法計算
- 不同產業本益比差異大（科技股通常比傳產高）
- 成長股可接受較高 P/E（未來 EPS 成長 → P/E 自然降低）
""")

    with st.expander("PEG 比率（Price/Earnings to Growth）"):
        st.markdown("""
**白話解說**

P/E 只看「現在」，PEG 把「成長速度」也納入評估。
> 「我花的本益比，是否被足夠的成長所支撐？」

PEG = 1 被視為合理估值；PEG < 1 暗示被低估；PEG > 2 可能昂貴。

**計算公式**
```
PEG = P/E ÷ EPS 年均成長率（%）

範例：P/E = 25 倍，EPS 成長率 = 30%
PEG = 25 ÷ 30 = 0.83  → 相對合理
```

**判讀標準**
| PEG | 意義 |
|-----|------|
| < 0.5 | 可能嚴重低估（或成長率預期過高） |
| 0.5–1 | 合理偏低 |
| 1–2   | 合理 |
| > 2   | 偏貴，需要高確定性的成長支撐 |

**注意**：成長率預估本身有不確定性，建議搭配多期 EPS 趨勢確認。
""")

    with st.expander("EV/EBITDA（企業價值倍數）"):
        st.markdown("""
**白話解說**

P/E 受資本結構影響（有沒有舉債）；EV/EBITDA 是更公平的跨公司比較工具。
- **EV（企業價值）**= 市值 + 淨負債（扣除現金）→ 「要買下這家公司要花多少？」
- **EBITDA**= 稅前息前折舊攤銷前盈餘 → 「公司實際賺錢能力，不管財務結構」

**計算公式**
```
EV = 市值 + 有息負債 - 現金及約當現金
EBITDA = 淨利 + 利息費用 + 稅 + 折舊 + 攤銷

EV/EBITDA = EV ÷ EBITDA
```

**判讀標準（依產業差異大）**
| EV/EBITDA | 意義 |
|-----------|------|
| < 5 倍   | 偏低（傳產、金融） |
| 8–15 倍  | 一般製造業合理範圍 |
| 15–25 倍 | 科技成長股 |
| > 25 倍  | 高成長或市場過度樂觀 |

**優點**：特別適合比較「不同資本結構」的公司（例如比較鴻海 vs 廣達）。
""")

    with st.expander("P/B 股價淨值比（Price-to-Book Ratio）"):
        st.markdown("""
**白話解說**

「帳面價值」就是公司把所有資產賣掉、還清所有債務後剩下的錢。P/B 告訴你：
> 「你花多少倍的帳面價值在買這家公司？」

P/B = 1 就是「用帳面價值買」；P/B = 3 就是「花 3 倍帳面價值買」。

**計算公式**
```
P/B = 每股股價 ÷ 每股帳面淨值
每股帳面淨值 = 股東權益 ÷ 流通股數
```

**判讀標準**
| P/B | 意義 |
|-----|------|
| < 1 | 股價低於清算價值，可能低估（需確認資產品質） |
| 1–2 | 合理 |
| 2–5 | 偏高，但 ROE 高則合理 |
| > 5 | 品牌溢價或市場過度樂觀 |

**搭配 ROE 使用**
> 粗略判斷：合理 P/B ≈ ROE ÷ 必要報酬率
""")

    with st.expander("ROE 股東權益報酬率（Return on Equity）"):
        st.markdown("""
**白話解說**

就像評估一家工廠「每投入 100 萬，能賺多少錢」。
ROE = 20% 代表你投入 100 萬的股東資金，公司每年能賺回 20 萬。

**計算公式**
```
ROE = 淨利 ÷ 股東權益 × 100%
```

**杜邦分解（更深入理解）**
```
ROE = 淨利率 × 資產周轉率 × 財務槓桿
     （賺多少）   （轉得快不快）  （借了多少槓桿）
```

**判讀標準**
| ROE | 意義 |
|-----|------|
| ≥ 20% | 優秀（巴菲特標準） |
| 15–20% | 良好 |
| 8–15%  | 普通 |
| < 8%   | 偏低 |

**注意**：高財務槓桿也會拉高 ROE，需搭配負債比率一起看。
""")

    with st.expander("應收帳款天數 DSO（Days Sales Outstanding）"):
        st.markdown("""
**白話解說**

賣出去了但錢還沒收到——應收帳款天數衡量公司「多快能收回現金」。
DSO 越短 = 收款能力強、客戶付款積極。
DSO 突然暴增 = 警示！可能有客戶付款問題，或業務依賴大客戶授信。

**計算公式**
```
DSO = 應收帳款 ÷ 日均營收
日均營收 = 年度營收 ÷ 365
```

**判讀標準（依產業而異）**
| DSO | 一般評估 |
|-----|---------|
| < 30 天 | 優秀（現金消費型、電商） |
| 30–60 天 | 正常製造業 |
| 60–90 天 | 偏高，需追蹤趨勢 |
| > 90 天  | 警示，需了解原因 |

**與庫存天數搭配**：DSO + 存貨天數 - 應付帳款天數 = **現金循環週期**（越短越健康）。
""")

    with st.expander("存貨週轉天數（Inventory Days / DIO）"):
        st.markdown("""
**白話解說**

存貨壓倉是資金的大敵。存貨天數衡量「原料買進來到賣出去要多少天」。
天數越短 = 存貨管理效率高、佔用資金少。

**計算公式**
```
存貨週轉天數 = 平均存貨 ÷ 日均銷貨成本
日均銷貨成本 = 年度銷貨成本 ÷ 365
```

**產業參考值**
| 產業 | 典型存貨天數 |
|------|------------|
| 電子代工（鴻海） | 20–35 天 |
| 半導體製造 | 60–90 天 |
| 零售百貨 | 30–60 天 |
| 航運公司 | 幾乎為零 |

**注意**：庫存突然增加 → 可能是需求下滑（去庫存壓力），下季毛利率承壓。
""")

    with st.expander("利息保障倍數（Interest Coverage Ratio）"):
        st.markdown("""
**白話解說**

公司賺到的錢夠不夠付利息？
利息保障倍數 = 1 表示剛好能付息；< 1 表示付不起，財務危機風險高。

**計算公式**
```
利息保障倍數 = EBIT（息前稅前利潤）÷ 利息費用
```

**判讀標準**
| 倍數 | 意義 |
|------|------|
| ≥ 10 倍 | 財務非常健康 |
| 3–10 倍 | 正常 |
| 1.5–3 倍 | 偏低，景氣下行時有壓力 |
| < 1.5 倍 | 危險，需密切追蹤 |

**升息環境下**：高負債公司的利息費用會增加，保障倍數下降，需特別留意。
""")

    with st.expander("自由現金流（FCF）& 現金流品質"):
        st.markdown("""
**白話解說**

淨利是帳面數字；自由現金流才是「口袋裡真正多出的錢」。

> FCF = 帳面獲利扣掉「維持或擴大業務所必須的投資」後剩下的現金。

**計算公式**
```
FCF = 營業現金流（OCF）- 資本支出（CapEx）
```

**現金流品質比率**
```
現金流品質 = OCF ÷ 淨利
```
| 比率 | 意義 |
|------|------|
| ≥ 1.0 | 優良：現金收入超過帳面獲利 |
| 0.7–1.0 | 正常 |
| < 0.7  | 警示：大量應計項目，需查原因 |
| 負值   | 危險：賺錢卻燒錢 |

**投資角度**：能持續產生正自由現金流的公司，才有條件穩定發股息、回購庫藏股。
""")

    with st.expander("毛利率 / 營業利益率 / 淨利率"):
        st.markdown("""
**白話解說**

想像一家麵包店：
- 賣一個麵包 50 元
- 麵粉等原料成本 20 元 → **毛利 30 元，毛利率 60%**
- 再扣掉店租、員工薪水 15 元 → **營業利益 15 元，營業利益率 30%**
- 再扣掉利息、稅後 → **淨利 12 元，淨利率 24%**

**三層公式**
```
毛利率     = （營收 - 直接成本）÷ 營收
營業利益率 = （毛利 - 費用）÷ 營收
淨利率     = 淨利 ÷ 營收
```

**各產業毛利率參考**
| 產業 | 典型毛利率 |
|------|-----------|
| 半導體（台積電）| 50–55% |
| IC 設計（聯發科）| 45–50% |
| 電子代工（鴻海）| 5–8%   |
| 電信（中華電）  | 20–35% |
| 零售百貨        | 30–40% |
""")

    with st.expander("負債比 / 流動比率 / 速動比率"):
        st.markdown("""
**負債權益比（D/E Ratio）**
```
D/E = 總負債 ÷ 股東權益
```
- D/E < 1：負債少，財務穩健
- D/E 1–2：適中，需看產業
- D/E > 3：財務槓桿高，利率風險大

**流動比率**（短期償債能力）
```
流動比率 = 流動資產 ÷ 流動負債
```
- > 2：充裕，短期無還債壓力
- 1–2：尚可
- < 1：可能有短期流動性問題

**速動比率**（更嚴格，排除存貨）
```
速動比率 = （流動資產 - 存貨）÷ 流動負債
```
- 通常需 > 1 才算安全

**Altman Z-Score（破產預測模型）**
```
Z = 1.2×A + 1.4×B + 3.3×C + 0.6×D + 1.0×E
A=流動資本/總資產、B=保留盈餘/總資產、C=EBIT/總資產
D=市值/總負債、E=營收/總資產
Z > 2.99：安全；1.81–2.99：灰色地帶；< 1.81：破產危險
```
""")

