with tab2:
    st.header("技術指標")

    with st.expander("移動平均線（MA / EMA）", expanded=True):
        st.markdown("""
**白話解說**

均線就像是計算你最近 20 天的平均體重，MA20 就是最近 20 個交易日的平均股價。

**常用均線**
| 均線 | 天數 | 意義 |
|------|------|------|
| MA5  | 5天  | 週線，極短期 |
| MA20 | 20天 | 月線，短期 |
| MA60 | 60天 | 季線，中期 |
| MA120| 120天 | 半年線 |
| MA240| 240天 | 年線，長期 |

**MA vs EMA**
- MA：每天等權重（簡單平均）
- EMA：越近的價格權重越高（對最新動態反應更快）

**判讀**
- 股價 > MA60：中期多頭格局
- 短線均線向上穿越長線均線 → **黃金交叉**（買入訊號）
- 短線均線向下穿破長線均線 → **死亡交叉**（賣出訊號）
- 多頭排列（MA5 > MA20 > MA60 > MA120）= 強勢上漲趨勢
""")

    with st.expander("均線乖離率（BIAS）"):
        st.markdown("""
**白話解說**

BIAS 衡量「現在的股價偏離均線有多遠（%）」。橡皮筋拉得越長，越容易彈回。

**計算公式**
```
BIAS = （股價 - MA）÷ MA × 100%
```

**判讀（以 MA20 為例）**
| BIAS | 意義 |
|------|------|
| > +10% | 嚴重超漲，有回調壓力 |
| +5% ~ +10% | 偏漲，注意 |
| -5% ~ +5% | 正常範圍 |
| -5% ~ -10% | 偏低，可能有支撐 |
| < -10% | 嚴重超跌，可能有反彈機會 |

**注意**：強勢趨勢中 BIAS 可以長期偏正；要搭配趨勢判斷，不能單獨作為買賣依據。
""")

    with st.expander("RSI 相對強弱指標（Relative Strength Index）"):
        st.markdown("""
**白話解說**

就像彈簧：拉得太緊（超買），容易彈回來；壓得太扁（超賣），容易反彈。
RSI 衡量「最近一段時間，上漲力道 vs 下跌力道，哪邊更強？」

**計算公式**
```
平均漲幅 = 近 14 天漲幅的平均值
平均跌幅 = 近 14 天跌幅的平均值
RS  = 平均漲幅 ÷ 平均跌幅
RSI = 100 - 100 ÷ (1 + RS)
```

**判讀**
| RSI | 意義 |
|-----|------|
| > 80 | 嚴重超買，短線有回調風險 |
| 70–80 | 超買區 |
| 50   | 多空分界線 |
| 20–30 | 超賣區 |
| < 20  | 嚴重超賣，可能出現反彈 |

**背離訊號（重要！）**
- 股價創新高，但 RSI 沒有創新高 → **頂背離**，可能即將轉跌
- 股價創新低，但 RSI 沒有創新低 → **底背離**，可能即將轉漲
""")

    with st.expander("MACD 指標"):
        st.markdown("""
**白話解說**

MACD 看的是「短期平均價格 vs 長期平均價格的差距」，以及這個差距是在擴大還是縮小。

**計算公式**
```
EMA12    = 12 日指數移動平均
EMA26    = 26 日指數移動平均
MACD 線  = EMA12 - EMA26
Signal 線 = MACD 的 9 日 EMA
柱狀體    = MACD 線 - Signal 線
```

**判讀**
| 現象 | 意義 |
|------|------|
| MACD 上穿 Signal（黃金交叉）| 短線買入訊號 |
| MACD 下穿 Signal（死亡交叉）| 短線賣出訊號 |
| 柱狀體從負轉正 | 動能從空轉多 |
| MACD 在零軸上方 | 整體趨勢偏多 |
| MACD 在零軸下方 | 整體趨勢偏空 |
""")

    with st.expander("KD 隨機指標（Stochastic Oscillator）"):
        st.markdown("""
**白話解說**

KD 問的問題是：「今天的收盤價，在過去 9 天的高低區間裡，位於哪個位置？」

**計算公式**
```
RSV = (今日收盤 - 近9日最低) ÷ (近9日最高 - 近9日最低) × 100
K 值 = RSV 的 3 日平滑移動平均
D 值 = K 值的 3 日平滑移動平均
```

**判讀**
| KD 區間 | 意義 |
|---------|------|
| K > 80, D > 80 | 超買，注意賣壓 |
| K < 20, D < 20 | 超賣，注意買機 |
| K 上穿 D       | 黃金交叉，短線轉強 |
| K 下穿 D       | 死亡交叉，短線轉弱 |

**適用場景**：適合震盪行情；強勢趨勢中 KD 可能長期超買，不適合單獨做空依據。
""")

    with st.expander("布林通道（Bollinger Bands）"):
        st.markdown("""
**白話解說**

在均線上下各畫一條「正常波動範圍」的邊界。
碰到上軌 → 偏貴；碰到下軌 → 偏便宜（相對近期波動）。

**計算公式**
```
中軌 = MA20
上軌 = MA20 + 2 × 20日標準差
下軌 = MA20 - 2 × 20日標準差
```

**通道寬度的意義**
- 通道變窄（壓縮）→ 波動率低，可能即將有大行情
- 通道變寬（擴張）→ 波動率高，趨勢加速

**判讀**
- 股價突破上軌且通道擴張 → 強勢多頭延續
- 股價跌破下軌且通道擴張 → 強勢空頭延續
- 碰到上軌但通道收縮 → 可能反轉
""")

    with st.expander("ATR 平均真實波幅（Average True Range）"):
        st.markdown("""
**白話解說**

ATR 衡量「每天的股價波動幅度有多大」——不管漲跌，只看幅度。
就像颱風的「風速」，不管颱風往哪個方向走，只看它有多強。

**計算公式**
```
真實波幅（TR）= max(
    今日最高 - 今日最低,
    |今日最高 - 昨日收盤|,
    |今日最低 - 昨日收盤|
)
ATR = TR 的 14 日移動平均
```

**用途**
1. **停損設置**：停損位 = 買進價 - 2×ATR（根據波動度客製化停損）
2. **判斷趨勢強弱**：ATR 上升 = 市場波動加大，趨勢可能加速
3. **比較不同股票風險**：ATR/股價 = 相對波動率
""")

    with st.expander("OBV 能量潮（On-Balance Volume）"):
        st.markdown("""
**白話解說**

OBV 把「成交量和股價方向」結合起來，看資金是在流入還是流出。
今天漲 → 成交量加；今天跌 → 成交量減。

**計算邏輯**
```
若今日收盤 > 昨日收盤：OBV = 昨日OBV + 今日成交量
若今日收盤 < 昨日收盤：OBV = 昨日OBV - 今日成交量
若今日收盤 = 昨日收盤：OBV = 昨日OBV（不變）
```

**判讀**
- OBV 持續上升，股價也上升 → 量價配合，趨勢健康
- OBV 上升，股價橫盤 → 可能準備突破
- **OBV 背離**：股價創新高，OBV 沒創新高 → 頂背離，注意轉折
""")

